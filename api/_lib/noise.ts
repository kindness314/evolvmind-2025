// ============================================================================
// 时间正则模式
// ============================================================================

const TIME_PATTERNS: RegExp[] = [
  // 时钟时间：00:40, 22:00, 3:30, 00：40（中文冒号）
  /^\d{1,2}[:：]\d{2}$/,
  // 数字+点：22点, 上午10点, 下午3点, 晚上8点, 凌晨4点, 10点半
  /^(凌晨|早上|上午|中午|下午|晚上|傍晚|夜里)?\d{1,2}点(半|多|过|左右)?$/,
  // 数字+点+数字+分：10点30分, 3点15分, 下午4点20分
  /^(凌晨|早上|上午|中午|下午|晚上|傍晚|夜里)?\d{1,2}点\d{1,2}分?$/,
  // 中文半点：十点半, 三点半
  /^[零一二三四五六七八九十]{1,2}点[半多]$/,
  // 中文月日组合：8月15日, 12月3号
  /^\d{1,2}月\d{1,2}[日号]$/,
  // 年份或年月：2025年, 2025年8月
  /^\d{4}年(\d{1,2}月)?$/,
  // 纯数字：1-4 位
  /^\d{1,4}$/,
  // 数字+量词（无上下文时无意义）：10个, 100元, 50%
  /^\d+[个只条次元块毛分角%％倍斤两克千克吨]$/,
  // 纯数字+时间单位：30分钟, 1小时, 3天
  // 章节碎片：第4章, 第三章（无书名/上下文时不构成洞察）
  /^第\d+[章节篇]$/,
  /^第[零一二三四五六七八九十百]+[章节篇]$/,
  /^\d+(\.\d+)?(分钟|小时|天|周|月|年|秒)$/,
];

// ============================================================================
// 包含式时间模式 — 检测嵌入在长名称中的噪声时间片段
// ============================================================================

/** 名称中包含这些模式之一 → 视为噪声时间节点 */
const TIME_CONTAINS_PATTERNS: RegExp[] = [
  /周[一二三四五六日][^\d]{0,3}(上|中|下)午\d{1,2}点/,
  // "每X" + "Y点" 结构：每[周|天|月]...N点
  /每[周天月年][^\d]*\d{1,2}点/,
  // 纯数字时间片段：任何上下文中的 "上午10点", "下午3点" 等
  /(凌晨|早上|上午|中午|下午|晚上|傍晚)[^\d]*\d{1,2}点/,
];

// ============================================================================

/** 计算名称剥离所有停用词和数字后的剩余长度（中文字符数）*/
function meaningfulLength(name: string): number {
  let s = name;
  // 按长度降序排，优先匹配长词避免 "下午" 被拆成单个字符
  const sorted = [...NODE_STOP_WORDS].sort((a, b) => b.length - a.length);
  for (const w of sorted) {
    s = s.replaceAll(w, '');
  }
  // 去掉数字和标点
  s = s.replace(/[\d.,;:!?，。；：！？、…—\-·'"'""''【】《》（）()\[\]{}<>+\s]+/g, '');
  // 去掉 VAGUE_TWO_CHAR 中的单字
  for (const v of VAGUE_TWO_CHAR) {
    s = s.replaceAll(v, '');
  }
  const chinese = s.match(/[\u4e00-\u9fff]/g);
  return chinese ? chinese.length : 0;
}
// ============================================================================
// 极短通用概念
// ============================================================================

const VAGUE_TWO_CHAR = new Set([
  '还行', '还好', '可以', '不错', '一般', '正常', '普通',
  '开心', '难过', '郁闷', '烦躁', '焦虑', '生气',
  '累', '困', '饿', '冷', '热', '忙', '闲',
  '对了', '错了',
]);

// ============================================================================
// 噪声捕获内容关键词 — 用于过滤 excerpts 中的垃圾记录
// ============================================================================

const NOISE_CAPTURE_KEYWORDS = [
  '无意义', '随便', '测试', 'test', '不知道写什么', '没什么', '没事',
  'asdf', 'qwer', 'test test', '不知道', '123', 'abc',
];

// ============================================================================
// 噪声捕获标题模式
// ============================================================================

const NOISE_CAPTURE_TITLE_PATTERNS: RegExp[] = [
  /^无意义/,
  /^随便/,
  /^测试/,
  /^test/i,
  /^\d+$/,
];

// ============================================================================
// 公开 API
// ============================================================================

export function isTrivialNodeName(name: string): boolean {
  const s = name.trim();
  if (!s) return true;

  // 1. 精确停用词匹配
  if (NODE_STOP_WORDS.has(s)) return true;

  // 2. 极短通用概念
  if (VAGUE_TWO_CHAR.has(s)) return true;

  // 3. 单字汉字无意义
  if (s.length === 1 && /^[\u4e00-\u9fff]$/.test(s)) return true;

  // 4. 纯标点或空白
  if (/^[\s.,;:!?，。；：！？、…—\-·'"'""''【】《》（）()\[\]{}<>+`~@#$%^&*=]+$/.test(s)) return true;

  // 5. 时间正则模式匹配（整串锚定）
  for (const re of TIME_PATTERNS) {
    if (re.test(s)) return true;
  }

  // 6. 包含式时间模式（嵌入在长名称中）
  for (const re of TIME_CONTAINS_PATTERNS) {
    if (re.test(s)) return true;
  }

  // 7. 有意义内容 ≤1：剥离噪声词后几乎无剩余 → 纯噪声
  if (meaningfulLength(s) <= 1) return true;

  return false;
}

/**
 * 判断一条捕获记录是否为噪声（标题或内容无信息量）
 */
export function isNoiseCapture(title: string, summary?: string, content?: string): boolean {
  const combined = `${title || ''} ${summary || ''} ${content || ''}`.toLowerCase().trim();
  if (!combined) return true;

  for (const kw of NOISE_CAPTURE_KEYWORDS) {
    if (combined.includes(kw.toLowerCase())) return true;
  }

  for (const re of NOISE_CAPTURE_TITLE_PATTERNS) {
    if (re.test(title)) return true;
  }

  return false;
}
